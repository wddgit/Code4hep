  class PodioOutputModule : public edm::one::OutputModule<> {
  public:
    PodioOutputModule(edm::ParameterSet const&);
    static void fillDescriptions(edm::ConfigurationDescriptions& descriptions);

  private:
    void write(edm::EventForOutput const& e) final;
    void writeLuminosityBlock(edm::LuminosityBlockForOutput const&) final;
    void writeRun(edm::RunForOutput const&) final;
    bool finalSelection(edm::ProductDescription const&) const final;
    void initialRegistry(edm::ProductRegistry const&) final;
    void reallyCloseFile() final;
    bool isFileOpen() const final { return !fileClosed_; }
    podio::Writer writer_;
    bool fileClosed_ = false;
    void addDroppedAncestorDescriptions();
    std::map<edm::BranchID, edm::ProductDescription> descriptions_;
    std::map<edm::BranchID, std::string> collectionNames_;
    // Non-alias event product descriptions from the full registry, including dropped
    // ones. Those referenced as parentage ancestors are saved, marked dropped, at close.
    std::map<edm::BranchID, edm::ProductDescription> ancestorCandidates_;
    std::map<edm::ProcessHistoryID, edm::ProcessHistory> histories_;
    ParentageDictionary parentages_;
    edm::ProductDescription const* inputHeader_ = nullptr;
    edm::EDGetToken inputHeaderToken_;
  };

  PodioOutputModule::PodioOutputModule(edm::ParameterSet const& iPSet)
      : edm::one::OutputModuleBase(iPSet),
        edm::one::OutputModule<>(iPSet),
        writer_{podio::makeWriter(iPSet.getUntrackedParameter<std::string>("fileName"),
                                  iPSet.getUntrackedParameter<std::string>("type"))} {}

  void PodioOutputModule::fillDescriptions(edm::ConfigurationDescriptions& oDesc) {
    edm::ParameterSetDescription pset;
    edm::one::OutputModule<>::fillDescription(pset);
    pset.addUntracked<std::string>("fileName")->setComment("The name of the file to write.");
    pset.addUntracked<std::string>("type", "default")
        ->setComment(
            "The type of the file to write, e.g. 'root'. The value of 'default' says the type should be based on the "
            "file extension in the name.");
    oDesc.addDefault(pset);
  }

  bool PodioOutputModule::finalSelection(edm::ProductDescription const& product) const {
    // An EDAlias is stored under its original product's collection name (see
    // initialRegistry), so podio collection IDs used by relations and links never change.
    std::string const& fullClassName = product.fullClassName();
    // An EDAlias's own labels do not name a podio collection; its storage name is
    // checked against the reserved name in initialRegistry.
    if (product.branchType() == edm::InEvent && !product.aliasForBranchID().isValid() &&
        product.moduleLabel() + product.productInstanceName() == "EventHeader" &&
        (product.produced() || fullClassName != "edm4hep::EventHeaderCollection")) {
      throw cms::Exception("Configuration")
          << "Duplicate podio collection name 'EventHeader': reserved for a nonproduced input "
             "edm4hep::EventHeaderCollection or the header automatically generated by PodioOutputModule; "
          << "module='" << product.moduleLabel() << "', process='" << product.processName()
          << "', instance='" << product.productInstanceName() << "', BranchID=" << product.branchID().id()
          << ", type='" << fullClassName << "', produced=" << product.produced()
          << ". Rename the module/product instance or change the output selection to remove the conflict.";
    }
    if (fullClassName == "edm::EndPathStatus" ||
        fullClassName == "edm::HLTPathStatus" ||
        fullClassName == "edm::TriggerResults") {
      return false;
    }
    try {
      auto const& typeName = typeNameConversion(fullClassName);

      auto factory = c4h::CollectionWrapperConverterBaseFactory::get();
      (void)factory->create(typeName);
    } catch (cms::Exception const&) {
      edm::LogWarning("UnstorableType") << "The type '" << fullClassName
                                        << "' is not registered with the C4H_COLLECTION macro so cannot be stored. It "
                                           "will not be consumed by this module.";
      return false;
    }
    return true;
  }

  void PodioOutputModule::initialRegistry(edm::ProductRegistry const& registry) {
    auto identity = [](edm::ProductDescription const& description) {
      return "module='" + description.moduleLabel() + "', process='" + description.processName() +
             "', instance='" + description.productInstanceName() + "', BranchID=" +
             std::to_string(description.branchID().id());
    };
    // EventHeader is required independently of outputCommands. Only an input
    // product with the exact reserved name/type can replace the generated header.
    for (auto const& entry : registry.productList()) {
      auto const& description = entry.second;
      if (description.branchType() == edm::InEvent && description.present() && !description.produced() &&
          !description.aliasForBranchID().isValid() &&
          description.moduleLabel() + description.productInstanceName() == "EventHeader" &&
          description.fullClassName() == "edm4hep::EventHeaderCollection") {
        if (inputHeader_) {
          throw cms::Exception("Configuration")
              << "Duplicate podio collection name 'EventHeader' for [" << identity(*inputHeader_)
              << "] and [" << identity(description)
              << "]. Rename the module/product instance or change the output selection to remove the conflict; "
                 "only one input EventHeader is supported, independently of outputCommands.";
        }
        inputHeader_ = &description;
      }
    }
    // Parents are recorded by original BranchID, so EDAliases are never ancestors.
    for (auto const& entry : registry.productList()) {
      auto const& description = entry.second;
      if (description.branchType() == edm::InEvent && !description.aliasForBranchID().isValid()) {
        ancestorCandidates_.emplace(description.branchID(), description);
      }
    }
    std::string const headerIdentity =
        inputHeader_ ? identity(*inputHeader_) : "automatically generated by PodioOutputModule (no EDM product identity)";
    std::map<std::string, std::string> usedNames{{"EventHeader", headerIdentity}};
    podio::CollectionIDTable ids;
    std::map<std::uint32_t, std::pair<std::string, std::string>> usedIDs{
        {ids.add("EventHeader"), {"EventHeader", headerIdentity}}};
    std::map<edm::BranchID, edm::ProductDescription const*> byBranchID;
    for (auto const& entry : registry.productList()) {
      byBranchID.emplace(entry.second.branchID(), &entry.second);
    }
    for (auto const& product : keptProducts()[edm::InEvent]) {
      auto const& description = *product.first;
      auto productIdentity = identity(description);
      auto name = description.moduleLabel() + description.productInstanceName();
      if (description.aliasForBranchID().isValid()) {
        // Store an EDAlias under its original's collection name so podio collection IDs,
        // and therefore relations and links, never change. In the current process the
        // original is produced here; when rewriting, it is a dropped input description.
        // The original's description is saved, marked dropped, so the alias can be rebuilt.
        auto const found = byBranchID.find(description.aliasForBranchID());
        if (found == byBranchID.end() || found->second->aliasForBranchID().isValid()) {
          throw cms::Exception("Configuration")
              << "EDAlias [" << productIdentity << "] refers to alias target BranchID "
              << description.aliasForBranchID().id()
              << ", which has no non-alias ProductDescription in the product registry.";
        }
        auto const& original = *found->second;
        name = original.moduleLabel() + original.productInstanceName();
        productIdentity += " (EDAlias stored under its original's collection name: " + identity(original) + ")";
        descriptions_.emplace(original.branchID(), original);
      }
      auto const [existingName, nameAdded] = usedNames.emplace(name, productIdentity);
      if (!nameAdded && !(inputHeader_ && description.branchID() == inputHeader_->branchID())) {
        throw cms::Exception("Configuration")
            << "Duplicate podio collection name '" << name << "' for [" << existingName->second
            << "] and '" << name << "' for [" << productIdentity
            << "]. Collection names are moduleLabel + productInstanceName; EventHeader is reserved for a "
               "nonproduced input edm4hep::EventHeaderCollection or the automatically generated header. "
               "Rename the module/product instance or change the output selection to remove the conflict.";
      }
      auto const id = ids.add(name);
      auto const [existingID, idAdded] = usedIDs.emplace(id, std::make_pair(name, productIdentity));
      if (!idAdded && existingID->second.first != name) {
        throw cms::Exception("Configuration")
            << "podio Murmur32 collection ID collision: '" << existingID->second.first << "' for ["
            << existingID->second.second << "] and '" << name << "' for [" << productIdentity
            << "] both have collection ID " << id
            << ". Rename the module/product instance or change the output selection to remove the conflict.";
      }
      descriptions_.emplace(description.branchID(), description);
      collectionNames_.emplace(description.branchID(), name);
    }
    if (inputHeader_ && !collectionNames_.count(inputHeader_->branchID())) {
      inputHeaderToken_ = consumes(edm::TypeToGet{inputHeader_->unwrappedTypeID(), edm::PRODUCT_TYPE},
                                  edm::InputTag{inputHeader_->moduleLabel(), inputHeader_->productInstanceName(),
                                                inputHeader_->processName()});
    }
  }

  void PodioOutputModule::write(edm::EventForOutput const& e) {
    auto factory = c4h::CollectionWrapperConverterBaseFactory::get();

    podio::Frame frame;
    EventParentage parentage;
    auto rememberHistory = [this](edm::OccurrenceForOutput const& occurrence) {
      auto history = occurrence.processHistory();
      auto const id = history.setProcessHistoryID();
      histories_.emplace(id, std::move(history));
      return historyIDString(id);
    };
    frame.putParameter(eventProcessHistoryKey, rememberHistory(e));
    frame.putParameter(runProcessHistoryKey, rememberHistory(e.getRun()));
    frame.putParameter(lumiProcessHistoryKey, rememberHistory(e.getLuminosityBlock()));
    frame.putParameter(luminosityBlockKey, std::to_string(e.luminosityBlock()));
    struct SelectedCollection {
      std::string name;
      std::unique_ptr<CollectionWrapperConverterBase> converter;
      podio::CollectionBase const* collection;
    };
    std::vector<SelectedCollection> selected;
    selected.reserve(keptProducts()[edm::InEvent].size());
    bool hasSubsets = false;
    for (auto const& product : keptProducts()[edm::InEvent]) {
      auto const& typeName = typeNameConversion(product.first->fullClassName());

      auto converter = factory->create(typeName);

      edm::TypeID const& tid = product.first->unwrappedTypeID();
      edm::EDGetToken const& token = product.second;
      edm::BasicHandle bh = e.getByToken(token, tid);

      // Provenance records are keyed by the original BranchID, including for an EDAlias.
      collectParentage(product.first->originalBranchID(), e.productProvenanceRetrieverPtr(), parentage, parentages_);

      auto const& collectionName = collectionNames_.at(product.first->branchID());
      podio::CollectionBase const* collection = nullptr;
      if (bh.isValid()) {
        assert(bh.wrapper());
        collection = converter->getCollection(*bh.wrapper());
        assert(collection);
        hasSubsets |= collection->isSubsetCollection();
      }
      selected.push_back({collectionName, std::move(converter), collection});
    }
    if (inputHeader_ && !inputHeaderToken_.isUninitialized()) {
      auto converter = factory->create("edm4hep::EventHeaderCollection");
      auto bh = e.getByToken(inputHeaderToken_, inputHeader_->unwrappedTypeID());
      auto const* collection = bh.isValid() ? converter->getCollection(*bh.wrapper()) : nullptr;
      if (collection)
        hasSubsets |= collection->isSubsetCollection();
      // This mandatory, selection-exempt header has no output product metadata
      // or parentage root, just like the generated header.
      selected.push_back({"EventHeader", std::move(converter), collection});
    }
    bool hasInputHeader = false;
    for (auto const& entry : selected) {
      if (entry.name == "EventHeader" && entry.collection) {
        auto const& headers = dynamic_cast<edm4hep::EventHeaderCollection const&>(*entry.collection);
        if (headers.empty() || !headers.at(0).isAvailable()) {
          throw cms::Exception("InvalidEventHeader")
              << "Input EventHeader for event " << e.id()
              << " must contain an available element at index 0 for PodioSource to read it. "
                 "An empty collection or unavailable first element cannot be replaced without changing input data.";
        }
        hasInputHeader = true;
      }
    }
    // All gets above run before validation/copying, including unscheduled producers.
    CollectionWrapperConverterBase::CollectionTargets targets;
    CollectionWrapperConverterBase::CollectionNames knownNames;
    std::unordered_map<uint32_t, uint32_t> outputTargetIDs;
    if (hasSubsets) {
      for (auto const& entry : selected) {
        podio::CollectionIDTable ids;
        auto const outputID = ids.add(entry.name);
        if (!entry.collection) {
          knownNames.emplace(outputID, entry.name);
        }
        if (entry.collection) {
          knownNames.emplace(entry.collection->getID(), entry.name);
          if (!entry.collection->isSubsetCollection()) {
            outputTargetIDs.emplace(entry.collection->getID(), outputID);
            auto const [existing, added] = targets.emplace(
                entry.collection->getID(), std::make_pair(entry.name, entry.collection));
            if (!added) {
              throw cms::Exception("InvalidSubset")
                  << "Selected owning collections '" << existing->second.first << "' and '" << entry.name
                  << "' have the same actual collection ID " << entry.collection->getID()
                  << ". Subset targets cannot be identified unambiguously.";
            }
          }
        }
      }
      for (auto const& entry : selected) {
        if (entry.collection && entry.collection->isSubsetCollection()) {
          entry.converter->validateSubset(*entry.collection, entry.name, targets, knownNames);
        }
      }
    }
    for (auto const& entry : selected) {
      if (entry.collection) {
        auto copiedCollection = entry.converter->copy(*const_cast<podio::CollectionBase*>(entry.collection));
        assert(copiedCollection);
        if (entry.collection->isSubsetCollection()) {
          // The payload's actual ID can differ from the fixed output-name ID.
          auto buffers = copiedCollection->getBuffers();
          for (auto& id : *buffers.references->front()) {
            id.collectionID = outputTargetIDs.at(id.collectionID);
          }
        }
        frame.put(std::move(copiedCollection), entry.name);
      } else if (entry.name != "EventHeader") {
        //Data product is missing, but we MUST include one
        auto empty = entry.converter->createEmpty();
        frame.put(std::move(empty), entry.name);
      }
    }
    if (hasSubsets) {
      class FrameProvider final : public podio::ICollectionProvider {
      public:
        explicit FrameProvider(podio::Frame const& frame, std::vector<SelectedCollection> const& selected) {
          for (auto const& entry : selected) {
            if (entry.collection && !entry.collection->isSubsetCollection()) {
              auto* collection = const_cast<podio::CollectionBase*>(frame.get(entry.name));
              collections_.emplace(collection->getID(), collection);
            }
          }
        }
        bool get(uint32_t id, podio::CollectionBase*& collection) const final {
          auto found = collections_.find(id);
          collection = found == collections_.end() ? nullptr : found->second;
          return collection != nullptr;
        }
      private:
        std::unordered_map<uint32_t, podio::CollectionBase*> collections_;
      } provider(frame, selected);
      // put/get do not call setReferences for inserted collections. Resolve only
      // copied subsets after every owner is present, leaving ordinary relations untouched.
      for (auto const& entry : selected) {
        if (entry.collection && entry.collection->isSubsetCollection()) {
          const_cast<podio::CollectionBase*>(frame.get(entry.name))->setReferences(&provider);
        }
      }
    }
    if (!hasInputHeader) {
      auto ehc = std::make_unique<edm4hep::EventHeaderCollection>();
      auto eh = ehc->create();
      eh.setEventNumber(e.id().event());
      eh.setRunNumber(e.id().run());
      eh.setTimeStamp(e.time().value());
      frame.put(std::move(ehc), "EventHeader");
    }
    saveEventParentage(frame, parentage, parentages_);
    writer_.writeEvent(frame);
  }
  void PodioOutputModule::writeLuminosityBlock(edm::LuminosityBlockForOutput const& lumi) {
    auto history = lumi.processHistory();
    auto const id = history.setProcessHistoryID();
    histories_.emplace(id, std::move(history));
  }
  void PodioOutputModule::writeRun(edm::RunForOutput const& run) {
    auto history = run.processHistory();
    auto const id = history.setProcessHistoryID();
    histories_.emplace(id, std::move(history));
  }

  void PodioOutputModule::addDroppedAncestorDescriptions() {
    // Save the identity of each recorded ancestor that is not a stored product, marked
    // dropped (no collection name), so provenance tools can label it and a rewrite of this
    // file keeps it. Restoring a description needs its type's registered converter;
    // ancestors of other types, or missing from the registry, stay unlabeled BranchIDs.
    auto factory = CollectionWrapperConverterBaseFactory::get();
    for (auto const& id : parentages_.parentBranchIDs()) {
      if (descriptions_.count(id))
        continue;
      auto const found = ancestorCandidates_.find(id);
      // Module labels of transient products may contain '_', which the stored
      // identity format cannot represent; such an ancestor stays an unlabeled BranchID.
      if (found == ancestorCandidates_.end() || found->second.moduleLabel().find('_') != std::string::npos)
        continue;
      try {
        (void)factory->create(typeNameConversion(found->second.fullClassName()));
      } catch (cms::Exception const&) {
        continue;
      }
      descriptions_.emplace(id, found->second);
    }
  }

  void PodioOutputModule::reallyCloseFile() {
    // Snapshot at close so configurations from later input files are included.
    auto metadata = saveParameterSets();
    addDroppedAncestorDescriptions();
    saveProductDescriptions(metadata, descriptions_, collectionNames_);
    saveProcessHistories(metadata, histories_);
    parentages_.save(metadata);
    writer_.writeFrame(metadata, podio::Category::Metadata);
    writer_.finish();
    fileClosed_ = true;
  }
